"""Single-file Kaggle bundles of the `dce` package (D-026).

The Kaggle harness stages exactly one tracked code file under src/. A bundle is a generated,
tracked script `src/dce/remote/bundles/<name>.py` that embeds every `src/dce/**/*.py` (except the
bundles themselves) as a deterministic base64 zip, extracts it at run time, checks the tree hash,
and runs one entry module as __main__. `tests/unit/test_bundle.py` fails if a committed bundle no
longer matches `src/`, so a bundle is always the committed source.

Build:
    python -m dce.remote.bundle <name> <entry.module>      # e.g. tier1_g2 dce.remote.tier1_g2
"""

from __future__ import annotations

import base64
import hashlib
import io
import sys
import zipfile
from pathlib import Path

SRC = Path(__file__).resolve().parents[2]          # src/
BUNDLE_DIR = SRC / "dce" / "remote" / "bundles"
EPOCH = (2020, 1, 1, 0, 0, 0)


def package_files() -> list[Path]:
    files = []
    for p in sorted((SRC / "dce").rglob("*.py")):
        rel = p.relative_to(SRC)
        if "__pycache__" in rel.parts or rel.parts[:3] == ("dce", "remote", "bundles"):
            continue
        files.append(p)
    return files


def tree_hash(items: list[tuple[str, bytes]]) -> str:
    digest = hashlib.sha256()
    for name, data in items:
        digest.update(name.encode() + b"\0" + hashlib.sha256(data).hexdigest().encode() + b"\n")
    return digest.hexdigest()


def render(entry: str) -> str:
    items = [(str(p.relative_to(SRC)), p.read_bytes()) for p in package_files()]
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for name, data in items:
            info = zipfile.ZipInfo(name, date_time=EPOCH)
            info.external_attr = 0o644 << 16
            zf.writestr(info, data, compress_type=zipfile.ZIP_DEFLATED, compresslevel=9)
    payload = base64.b64encode(buf.getvalue()).decode("ascii")
    lines = [payload[i : i + 100] for i in range(0, len(payload), 100)]
    th = tree_hash(items)
    return f'''# GENERATED by `python -m dce.remote.bundle` — do not edit (D-026).
# Entry module: {entry}
# Tree hash of src/dce (excluding bundles): {th}
import base64, hashlib, io, os, runpy, sys, tempfile, zipfile

ENTRY = {entry!r}
TREE_HASH = {th!r}
PAYLOAD = (
''' + "\n".join(f'    "{ln}"' for ln in lines) + '''
)


def _extract():
    root = tempfile.mkdtemp(prefix="dce_bundle_")
    items = []
    with zipfile.ZipFile(io.BytesIO(base64.b64decode(PAYLOAD))) as zf:
        for name in sorted(zf.namelist()):
            data = zf.read(name)
            items.append((name, data))
            path = os.path.join(root, name)
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "wb") as fh:
                fh.write(data)
    digest = hashlib.sha256()
    for name, data in items:
        digest.update(name.encode() + b"\\0" + hashlib.sha256(data).hexdigest().encode() + b"\\n")
    if digest.hexdigest() != TREE_HASH:
        raise SystemExit("bundle tree hash mismatch")
    return root


sys.path.insert(0, _extract())
os.environ["DCE_BUNDLE_TREE_HASH"] = TREE_HASH
runpy.run_module(ENTRY, run_name="__main__", alter_sys=True)
'''


def bundle_path(name: str) -> Path:
    return BUNDLE_DIR / f"{name}.py"


def build(name: str, entry: str) -> Path:
    path = bundle_path(name)
    path.write_text(render(entry))
    return path


def entry_of(path: Path) -> str:
    for line in path.read_text().splitlines():
        if line.startswith("ENTRY = "):
            return eval(line.split("=", 1)[1])  # a repr'd string literal written by render()
    raise ValueError(f"no ENTRY in {path}")


if __name__ == "__main__":
    print(build(sys.argv[1], sys.argv[2]))
